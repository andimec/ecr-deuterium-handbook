new_sol=r'''  } else {
    // EXACT magnitude constraints for two coils, with no projection approximation:
    // |I1*v1 + I2*v2|^2 = Btarget^2 at each point.
    // For nonzero I1, t=I2/I1, and eliminating I1^2 gives a quadratic in t.
    // The I1=0 limiting case is checked separately. Up to four isolated roots.
    const targets=[B1,B2];
    const v=[[p1c1,p1c2],[p2c1,p2c2]];
    const coeffs=v.map(([a,b])=>({
      A:a.br*a.br+a.bz*a.bz,
      C:b.br*b.br+b.bz*b.bz,
      D:2*(a.br*b.br+a.bz*b.bz)
    }));
    const [q1,q2]=coeffs;
    const Q=(q,t)=>q.A+q.D*t+q.C*t*t;
    const k2=B1*B1*q2.C-B2*B2*q1.C;
    const k1=B1*B1*q2.D-B2*B2*q1.D;
    const k0=B1*B1*q2.A-B2*B2*q1.A;
    const scale=Math.max(Math.abs(k2),Math.abs(k1),Math.abs(k0),1e-28);
    const roots=[];
    if (Math.abs(k2)<scale*1e-11){
      if (Math.abs(k1)>scale*1e-11) roots.push(-k0/k1);
      else if(Math.abs(k0)<scale*1e-11){
        res.innerHTML='<span style="color:#fda">Restricciones dependientes: soluciones continuas posibles; elija puntos independientes.</span>';
        return;
      }
    }else{
      const disc=k1*k1-4*k2*k0;
      if(disc>=-1e-12*scale*scale){
        const ds=Math.sqrt(Math.max(0,disc));
        roots.push((-k1+ds)/(2*k2));
        if(ds>0)roots.push((-k1-ds)/(2*k2));
      }
    }
    const candidates=[];
    if(B1>0){
      for(const t of roots){
        const q=Q(q1,t);
        if(q<=0 || !Number.isFinite(q))continue;
        const c=B1/Math.sqrt(q);
        candidates.push({i1:c,i2:c*t},{i1:-c,i2:-c*t});
      }
      if(Math.abs(k2)<scale*1e-10 && q1.C>0){
        const c=B1/Math.sqrt(q1.C);
        candidates.push({i1:0,i2:c},{i1:0,i2:-c});
      }
    }else if(B2===0){
      candidates.push({i1:0,i2:0});
    }
    const verified=[];
    for(const p of candidates){
      if(!Number.isFinite(p.i1)||!Number.isFinite(p.i2)||Math.max(Math.abs(p.i1),Math.abs(p.i2))>150)continue;
      const m=(a,b)=>Math.hypot(p.i1*a.br+p.i2*b.br,p.i1*a.bz+p.i2*b.bz);
      if(Math.abs(m(p1c1,p1c2)-B1)>Math.max(1e-8,1e-5*B1))continue;
      if(Math.abs(m(p2c1,p2c2)-B2)>Math.max(1e-8,1e-5*B2))continue;
      if(verified.some(s=>Math.hypot(s.i1-p.i1,s.i2-p.i2)<0.01))continue;
      verified.push(p);
    }
    solutions=verified.sort((a,b)=>(a.i1>=0&&a.i2>=0?0:1)-(b.i1>=0&&b.i2>=0?0:1))
      .map((c,i)=>({...c,label:`root ${i+1}`}));
  }
'''
